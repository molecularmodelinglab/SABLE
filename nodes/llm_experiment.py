import json
import os
import random
import re
import sys
from abc import ABC, abstractmethod
from typing import Any, Dict, List, Optional
import yaml

sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


from schemas.state import ExperimentResult, WorkflowState


class LLMProvider(ABC):
    """Abstract base class defining the interface for an LLM provider."""

    @abstractmethod
    def generate(self, prompt: str, system_prompt: Optional[str] = None) -> str:
        """
        Generates a response from the LLM given a prompt.

        Args:
            prompt: The main user prompt for the LLM.
            system_prompt: An optional system-level instruction to guide the model's behavior.

        Returns:
            The text response generated by the LLM.
        """
        pass


class GeminiProvider(LLMProvider):
    """LLM provider implementation for Google Gemini."""

    def __init__(self):
        """Initializes the Gemini model, loading the API key from a config file."""
        self.model = None
        try:
            import google.generativeai as genai

            with open("config.yml") as f:
                config = yaml.safe_load(f)
            api_key = config.get("api_credentials", {}).get("google_gemmini", {}).get("api_key")

            if not api_key:
                raise ValueError("Gemini API key not found in config.yml")

            genai.configure(api_key=api_key)
            self.model = genai.GenerativeModel("gemini-1.5-flash")
        except (ImportError, FileNotFoundError, ValueError) as e:
            print(f"Warning: Could not initialize GeminiProvider. {e}")

    def generate(self, prompt: str, system_prompt: Optional[str] = None) -> str:
        """Generates a response using the configured Gemini model."""
        if not self.model:
            return '{"error": "Gemini model is not initialized."}'

        full_prompt = f"{system_prompt}\n\n{prompt}" if system_prompt else prompt
        response = self.model.generate_content(full_prompt)
        return response.text


class MockProvider(LLMProvider):
    """A mock LLM provider for testing and development purposes."""

    def generate(self, prompt: str, system_prompt: Optional[str] = None) -> str:
        """Generates a predictable, mock JSON response with simulated properties."""
        smiles_pattern = r"[A-Z][A-Za-z0-9@+\-\[\]()=#%]{5,}"
        molecules = re.findall(smiles_pattern, prompt)

        results = {}
        for mol in molecules[:5]:  # Limit to 5 molecules for brevity
            results[mol] = {
                "QED": round(random.uniform(0.3, 0.9), 3),
                "TPSA": round(random.uniform(20, 140), 1),
                "LogP": round(random.uniform(-2, 5), 2),
                "Solubility": round(random.uniform(-5, 2), 2),
            }

        return json.dumps(
            {
                "thought": "This is a mock response from the testing provider.",
                "results": results,
            }
        )


def parse_llm_response(
    response_text: str, molecule_smiles: List[str], property_names: List[str]
) -> Dict[str, Dict[str, float]]:
    """
    Parses the raw text response from an LLM to extract property values.

    This function first attempts to parse the entire response as a JSON object.
    If that fails, it falls back to using regular expressions to find property
    values in plain text, which is common in ReACT-style outputs.

    Args:
        response_text: The raw string returned by the LLM.
        molecule_smiles: A list of SMILES strings that were sent in the prompt.
        property_names: A list of property names that were requested.

    Returns:
        A dictionary mapping SMILES strings to their predicted properties.
    """
    # Attempt to parse the response as JSON first.
    try:
        data = json.loads(response_text)
        if "results" in data and isinstance(data["results"], dict):
            return data["results"]
    except json.JSONDecodeError:
        pass  # Fallback to regex parsing if JSON fails.

    # Regex fallback for non-JSON or malformed JSON responses.
    parsed_results = {}
    for smiles in molecule_smiles:
        mol_properties = {}
        for prop in property_names:
            patterns = [
                rf"{prop}[-:\s]+([0-9.-]+)",
                rf"{prop.lower()}[-:\s]+([0-9.-]+)",
                rf"{prop.upper()}[-:\s]+([0-9.-]+)",
            ]
            for pattern in patterns:
                match = re.search(pattern, response_text, re.IGNORECASE)
                if match:
                    try:
                        mol_properties[prop] = float(match.group(1))
                        break  # Stop after the first successful pattern match for this prop.
                    except (ValueError, IndexError):
                        continue
        if mol_properties:
            parsed_results[smiles] = mol_properties

    return parsed_results


def llm_experiment_node(state: WorkflowState) -> Dict[str, Any]:
    """
    Simulates experiments by querying an LLM for molecular property predictions.

    Args:
        state: The current state of the molecular optimization workflow.

    Returns:
        A dictionary containing the updated workflow state.
    """
    state.log("llm_experiment_started", {"molecules_to_test": state.current_bo_recommendations})

    if not state.current_bo_recommendations:
        state.log("llm_experiment_skipped", "No new molecules were recommended for testing.")
        return {"state": state}

    # Retrieve molecule SMILES strings from the search space.
    molecules_to_test = [
        state.search_space[mol_id]
        for mol_id in state.current_bo_recommendations
        if mol_id in state.search_space
    ]
    if not molecules_to_test:
        state.log("llm_experiment_error", "Could not find recommended molecules in search space.")
        return {"state": state}

    # Initialize the LLM provider, with a fallback to the mock provider on failure.
    llm = GeminiProvider()
    if not llm.model:
        state.log("llm_experiment_fallback", "Using MockProvider due to Gemini initialization failure.")
        llm = MockProvider()

    property_names = [t.name for t in state.targets]
    use_react = state.parsed_arguments.get("use_react", True)

    # Construct the appropriate prompt for the selected mode (ReACT vs. Direct JSON).
    if use_react:
        system_prompt = """You are a computational chemistry expert using the ReACT pattern.
        Format your response as:
        Thought: [Your reasoning about the molecular properties]
        Action: Analyze molecular properties
        Observation: [The calculated/estimated property values for each molecule]"""
        prompt = (
            f"Analyze these molecules and estimate their properties: {property_names}\n\n"
            f"Molecules (SMILES):\n"
            + "\n".join(f"- {s}" for s in molecules_to_test)
        )
    else:
        system_prompt = "You are a computational chemistry expert. Provide property estimates in JSON."
        prompt = (
            f"Estimate these properties for the given molecules: {property_names}\n\n"
            f"Molecules (SMILES):\n"
            + "\n".join(f"{i+1}. {s}" for i, s in enumerate(molecules_to_test))
            + '\n\nReturn a JSON object with the structure: {"results": {"SMILES": {"PROP": value}}}'
        )

    # Generate and process the LLM response.
    try:
        response_text = llm.generate(prompt, system_prompt)
        state.llm_history.append(
            {"iteration": state.current_iteration, "prompt": prompt, "response": response_text}
        )
        parsed_results = parse_llm_response(response_text, molecules_to_test, property_names)

        # Update the workflow state with the new experimental results.
        for mol_id in state.current_bo_recommendations:
            smiles = state.search_space.get(mol_id)
            if smiles in parsed_results:
                result = ExperimentResult(
                    molecule_id=mol_id,
                    smiles=smiles,
                    iteration=state.current_iteration,
                    properties=parsed_results[smiles],
                    source="llm_simulation",
                )
                state.add_experimental_result(result)

        state.log("llm_experiment_completed", {"molecules_tested": len(parsed_results)})
    except Exception as e:
        state.log("llm_experiment_error", f"An error occurred during LLM interaction: {e}")

    return state
